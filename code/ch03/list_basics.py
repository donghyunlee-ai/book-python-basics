# ch03-01 리스트 — 여러 값을 한 그릇에
# 본문 셀 순서대로. python3로 실행 검증 (셀 1은 출력 없음).

# --- 셀 1: 이름표 다섯 개 — 번거로움의 실물 (출력 없음) ---
score1 = 85
score2 = 90
