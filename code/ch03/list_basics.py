# --- 셀 2: 대괄호가 리스트를 만든다 ---
scores = [85, 90, 70, 95, 80]
print(scores)
# 검증 출력: [85, 90, 70, 95, 80]

# --- 셀 3: type과 len — 같은 함수가 그대로 통한다 ---
print(type(scores))
print(len(scores))
# 검증 출력: <class 'list'>
# 검증 출력: 5

# --- 셀 4: 아무 자료형이나, 섞어서도 담긴다 ---
mixed = [1, "둘", 3.0]
print(mixed)
# 검증 출력: [1, '둘', 3.0]  (리스트 속 문자열은 작은따옴표 포장으로 표시됨 — 본문 처리)

# --- 셀 5: 빈 리스트 ---
todo = []
print(todo)
print(len(todo))
# 검증 출력: []
# 검증 출력: 0
