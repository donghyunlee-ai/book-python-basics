# ch03-07 [AI와 짝 코딩] 리스트 다루기 요청 — 복사인가 별칭인가 (코너 오답 코드 원본)
# 검증: python3 (2026-07-11)
# 출력: [70, 80, 85, 90, 95]

# 코너 오답 코드 — "백업해 두고 원본을 정렬해줘"에 대해 AI가 내놓기 쉬운 별칭 코드.
# backup = scores 는 복사가 아니라 같은 그릇에 이름표 하나 더 붙이는 별칭(05절).
# sort()는 제자리에서 바꾸는 도구(04절)라 하나뿐인 그릇의 속이 바뀌고,
# 두 이름표가 함께 바뀐 속을 본다 — 에러 없이 백업이 사라지는 조용한 오류.
scores = [85, 90, 70, 95, 80]
backup = scores
scores.sort()
print(backup)   # 출력: [70, 80, 85, 90, 95]  (원래 순서 [85, 90, 70, 95, 80]이 아님 — 백업 실패)

# 대조용 정답 — copy()면 원본 순서가 남는다 (본문 코드 블록에는 싣지 않음, 산문 언급용 검증)
scores2 = [85, 90, 70, 95, 80]
backup2 = scores2.copy()
scores2.sort()
assert scores2 == [70, 80, 85, 90, 95]
assert backup2 == [85, 90, 70, 95, 80]

# 본문 좋은 요청의 예시 입력/기대 출력 쌍 검증: [85, 90, 70] -> 정렬 [70, 85, 90] / 백업 [85, 90, 70]
sample = [85, 90, 70]
sample_backup = sample.copy()
sample.sort()
assert sample == [70, 85, 90]
assert sample_backup == [85, 90, 70]
