# 3장 5절 이름표 둘, 그릇 하나 — 별칭과 복사
# 책의 셀 순서대로.

# --- 셀 1: 별칭 충격 실물 — b만 바꿨는데 a도 바뀐다 ---
a = [10, 20, 30]
b = a
b.append(40)
print(b)   # [10, 20, 30, 40]
print(a)   # [10, 20, 30, 40]  ← 충격 지점

# --- 셀 2: 숫자 대조 — 재할당은 이름표 옮기기라 b는 그대로 ---
a = 10
b = a
a = a + 1
print(a)   # 11
print(b)   # 10

# --- 셀 3: 진짜 복사 — copy() 후 원본 무사 ---
a = [10, 20, 30]
b = a.copy()
b.append(40)
print(b)   # [10, 20, 30, 40]
print(a)   # [10, 20, 30]

# --- 셀 4: 전부 슬라이스 [:] — 같은 효과의 복사 관용구 ---
c = a[:]
c.append(99)
print(c)   # [10, 20, 30, 99]
print(a)   # [10, 20, 30]

# --- 더 알아보기: 책의 설명을 직접 확인하는 코드(책에는 없음) ---
# 별칭은 대등 — a 쪽을 고쳐도 b가 바뀐다
a = [10, 20, 30]
b = a
a.append(50)
assert b == [10, 20, 30, 50], b   # 통과: 거꾸로 방향도 함께 바뀜

# --- 셀 5: 얕은 복사 관찰 — 겉그릇만 새것, 속 그릇은 공유 ---
pairs = [[1, 2], [3, 4]]
backup = pairs.copy()
pairs[0].append(99)
print(pairs)    # [[1, 2, 99], [3, 4]]
print(backup)   # [[1, 2, 99], [3, 4]]  ← 복사본까지 바뀜
