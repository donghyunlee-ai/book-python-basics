# [셀 3]
# 숫자를 뒤에서부터 한 자리씩 떼어내서 출력하기
n = 379
while n:
    last_digit = n % 10
    print("떼어낸 숫자:", last_digit)
    n = n // 10

# [셀 4]
# 합이 처음으로 100을 넘는 순간 찾기
total = 0
num = 1

while total <= 100:
    total += num
    num += 1

print("100을 넘긴 숫자:", num - 1)
print("그때의 합:", total)
