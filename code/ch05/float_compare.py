# 5장 4절 소수의 어림값 — 같은지 묻기 전에

# 셀 1 — 2장에서 보았던 소수의 덧셈 결과를 다시 확인합니다.
print(0.1 + 0.2)  # 0.30000000000000004

# 셀 2 — 0.1 더하기 0.2는 0.3과 같은지 파이썬에게 묻습니다.
print(0.1 + 0.2 == 0.3)  # False

# 셀 3 — 두 어림값을 각각 소수점 둘째 자리에서 반올림한 뒤 비교합니다.
print(round(0.1 + 0.2, 2) == round(0.3, 2))  # True

# 셀 4 — 두 값의 차이에서 부호를 떼고, 그 크기가 0.000001보다 작은지 묻습니다.
a = 0.1 + 0.2
b = 0.3
print(abs(a - b) < 0.000001)  # True
