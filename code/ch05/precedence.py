# 5장 2절 계산 순서 — 우선순위와 괄호

# 셀 1 — 덧셈, 곱셈, 뺄셈, 나눗셈이 섞인 식의 계산 순서
print(3 + 5 * 2 - 8 / 4)  # 11.0

# 셀 2 — 괄호를 넣어 같은 식을 의도대로 갈라 보기
print(3 + (5 * 2) - (8 / 4))  # 11.0

# 셀 3 — 직관과 다르게 계산되어 '조용한 오류'를 낳는 두 식
print(-2 ** 2)      # -4 (거듭제곱이 음수 기호보다 먼저)
print(2 ** 3 ** 2)   # 512 (**는 오른쪽부터: 2 ** (3 ** 2))

# 셀 4 — 괄호 유무에 따른 계산 결과와 가독성의 차이
a = 80
b = 90
print(a + b / 2)     # 125.0
print((a + b) / 2)   # 85.0
