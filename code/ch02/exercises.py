# 2장 연습문제

# 문항 1 — 해설 예시 답 (이름 "김파이", 태어난 해 2005 — 나이는 중괄호 속 계산식)
name = "김파이"
birth = 2005
print(f"저는 {name}, 올해 {2026 - birth}살입니다")  # 출력: 저는 김파이, 올해 21살입니다

# 문항 2 — 리뷰 대상 코드: 에러 없이 실행되지만 하나 어긋남 (07절 [AI와 짝 코딩]에서 본 것과 같은 실수)
# 의도: 뒷 단어 "World" / 실제 출력: "Worl" — 끝 인덱스 10이 포함되지 않음(끝 미포함)
s = "Hello_World"
print(s[6:10])   # 출력: Worl  (의도한 "World"가 아님 — 검산: 10 - 6 = 4글자, 원한 것은 5글자)

# 문항 2 — 두 가지 수정 (해설 순서와 동일: ① 끝 번호 바로잡기 ② 끝 생략)
print(s[6:11])   # 출력: World  (d의 인덱스 10보다 하나 큰 11 — 끝 눈금 11은 존재)
print(s[6:])     # 출력: World  (생략은 "되는 데까지")

# 문항 3 — 리뷰 대상 코드: 에러 없이 실행되지만 의도(12 x 3 = 36)와 다름
a = "12"
b = 3
print(a * b)     # 출력: 121212  (문자열 * 정수 = 반복 — "12"가 세 번)

# 문항 3 — 고친 코드: 변환은 재할당해야 완성
a = "12"
a = int(a)
print(type(a))   # 출력: <class 'int'>  (변환 전후 type 확인 습관)
print(a * b)     # 출력: 36

# 문항 4 — 예측형: 간격(역방향·건너뛰기) 규칙 점검. 따옴표 문자열에 바로 대괄호 — 대괄호는 값에 붙는다.
print("파이썬"[::-1])         # 출력: 썬이파
print("Hello_World"[2:9:2])   # 출력: loWr  (인덱스 2, 4, 6, 8 — 눈금 9 앞에서 멈춤)
