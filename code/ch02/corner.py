# 2장 7절 [AI와 짝 코딩] 문자열 처리 요청 — 인덱스 경계를 의심하라 (AI가 내놓기 쉬운 오답 코드)
# 출력: ello / Hello / _B

# 오답 코드 — "앞 단어만 잘라줘"에 대해 AI가 내놓기 쉬운 하나 어긋난 코드.
# 사람 셈("1번째 글자부터 5번째 글자까지")을 그대로 옮긴 꼴: 빠진 것은 첫 글자 H 하나로,
# 범인은 0부터 규칙(사람의 1번째 = 파이썬 인덱스 0). 끝의 5는 사람 셈의 끝 포함과
# 파이썬의 끝 미포함이 상쇄되어 우연히 맞았다 — 다섯 번째 글자 o는 담긴다.
# 에러 없이 실행된다 — 04절에서 본 "조용한 오답" 그대로다.
s = "Hello_World"
word = s[1:5]
print(word)         # 출력: ello  (의도한 "Hello"가 아님)

# 참고: 바르게 고친 코드(책에서는 해설로 설명합니다)
print(s[0:5])       # 출력: Hello

# 짧은 입력으로 확인 — 책의 "좋은 요청" 팁에 나온 예시 쌍("A_B" -> 기대 "A")에 오답 코드를 적용.
# 긴 문자열에서는 그럴듯하던 하나 어긋남이 짧은 입력에서 뚜렷이 드러난다.
print("A_B"[1:5])   # 출력: _B  (기대한 "A"가 아님)
