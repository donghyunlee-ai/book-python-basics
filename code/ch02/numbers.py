# ch02-02 숫자 — int와 float (노트북 셀 기준 원본, 6셀 구성)
# 검증: python3 + IPython InteractiveShell 9.12.0 (2026-07-07)
# 출력: <class 'int'> / <class 'float'> / 1024 / 1267650600228229401496703205376
#       / 3.0 / 3.5 / 4.0 / 0.30000000000000004

# 셀 1 — 2와 2.0의 자료형: 같은 크기, 다른 자료형(.0은 신분증)
print(type(2))      # 출력: <class 'int'>
print(type(2.0))    # 출력: <class 'float'>

# 셀 2 — 거듭제곱 **: 예측-실행-대조 (2 * 10으로 잘못 읽으면 20)
print(2 ** 10)      # 출력: 1024

# 셀 3 — int는 크기 제한·어림 없이 정확 (셀 6의 float 어림값과 대비 축)
print(2 ** 100)     # 출력: 1267650600228229401496703205376 (31자리)

# 셀 4 — /의 결과는 언제나 float: 나누어떨어져도 .0
print(6 / 2)        # 출력: 3.0

# 셀 5 — int와 float가 섞이면 결과는 float (2 + 2.0은 절 개막 소재의 회수)
print(3 + 0.5)      # 출력: 3.5
print(2 + 2.0)      # 출력: 4.0

# 셀 6 — float는 어림값이 될 수 있다: 관찰+안심까지만, 원리·비교 주의는 ch05 소관
print(0.1 + 0.2)    # 출력: 0.30000000000000004
