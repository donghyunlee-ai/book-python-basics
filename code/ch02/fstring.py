# 2장 5절 f-string — 출력을 조립하다
# 출력: 나이: 20 / 제 나이는 20살입니다 / 제 나이는 20살입니다 / 제 나이는 {age}살입니다
#       / 내년이면 21살이 됩니다 / 1년은 52.142857142857146주입니다 / 1년은 52.1주입니다 / 나이: 20

# 셀 1 — str() 응급처치: 03절의 print("나이: " + 20) TypeError를 첫 갈래(변환)로 해결
age = 20
print("나이: " + str(age))          # 출력: 나이: 20

# 셀 2 — + 조립의 불편 실물: 숫자마다 str(), 문장이 세 토막
print("제 나이는 " + str(age) + "살입니다")   # 출력: 제 나이는 20살입니다

# 셀 3 — f-string 기본: 따옴표 앞 f + 값 자리 {변수} (셀 2와 1:1 대비, 같은 출력)
print(f"제 나이는 {age}살입니다")   # 출력: 제 나이는 20살입니다

# 셀 4 — 흔한 실수: f를 빠뜨리면 에러 없이 중괄호가 글자 그대로 찍힌다 ("조용한 오류")
print("제 나이는 {age}살입니다")   # 출력: 제 나이는 {age}살입니다

# 셀 5 — 중괄호 안에는 식도 들어간다 (02절 산술의 재사용)
print(f"내년이면 {age + 1}살이 됩니다")   # 출력: 내년이면 21살이 됩니다

# 셀 6 — 콜론 뒤 .1f: float 출력 다듬기 (02절 지저분한 float의 실용 보상)
print(f"1년은 {365 / 7}주입니다")       # 출력: 1년은 52.142857142857146주입니다
print(f"1년은 {365 / 7:.1f}주입니다")   # 출력: 1년은 52.1주입니다

# 참고 — %-포맷팅은 남의 코드에서 알아보는 정도로만 익힌다(직접 쓰지는 않는다)
print("나이: %d" % age)   # 출력: 나이: 20
