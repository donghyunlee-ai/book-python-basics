# ch04-03 딕셔너리 들여다보기 — in, len, 세 가지 목록
# 본문 셀 원본. python3 실행 검증용.
# phone 상태 기준: ch04-02절 끝 = {"김파이": "010-1234-5678", "이코드": "010-1111-2222"} 2쌍
# (02절에서 박튜플은 pop으로 제거, 이코드는 새 번호로 수정, 김파이는 원래 번호 보전)

# [셀 1] phone 재생성(새 세션 대비) + len = 쌍의 개수
phone = {"김파이": "010-1234-5678", "이코드": "010-1111-2222"}
print(len(phone))
# 출력: 2

# [셀 2] in은 키만 본다 — 예측-실행-대조
print("김파이" in phone)
print("010-1234-5678" in phone)
# 출력: True
# 출력: False  (저장돼 있는 번호인데도 False — in의 질문은 "이 이름표가 있느냐")

# [셀 3] 값을 검사하려면 값의 목록에 묻는다
print("010-1234-5678" in phone.values())
# 출력: True

# [셀 4] keys()가 돌려주는 특별한 목록 + list() 변환
print(phone.keys())
print(list(phone.keys()))
# 출력: dict_keys(['김파이', '이코드'])
# 출력: ['김파이', '이코드']

# [셀 5] values()·items() — items의 항목은 (키, 값) 튜플
print(list(phone.values()))
print(list(phone.items()))
# 출력: ['010-1234-5678', '010-1111-2222']
# 출력: [('김파이', '010-1234-5678'), ('이코드', '010-1111-2222')]
