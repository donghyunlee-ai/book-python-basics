# 4장 1절 번호가 아니라 이름표로 — 딕셔너리
# 출력: 010-9876-5432 / <class 'dict'> /
#       010-9876-5432, 010-1234-5678 / {'김파이': 95}
# 참고: phone 딕셔너리(김파이·이코드 2쌍)는 02·03절에서도 이어 쓴다.

# 셀 1 — 리스트 두 개로 만든 전화번호부: 이코드의 번호를 꺼내려면
#        이코드가 몇 번째인지 "내가" 기억하고 있어야 한다
names = ["김파이", "이코드"]
numbers = ["010-1234-5678", "010-9876-5432"]
print(numbers[1])    # 출력: 010-9876-5432

# 셀 2 — 딕셔너리 생성: 키(이름표)와 값을 콜론으로 잇고, 쌍 사이는 쉼표
phone = {"김파이": "010-1234-5678", "이코드": "010-9876-5432"}
print(type(phone))    # 출력: <class 'dict'>

# 셀 3 — 조회: 같은 대괄호, 다른 질문 — "몇 번째?"가 아니라 "무슨 이름표?"
print(phone["이코드"])    # 출력: 010-9876-5432
print(phone["김파이"])    # 출력: 010-1234-5678

# 셀 4 — 키 유일: 같은 키를 두 번 쓰면 에러 없이 마지막 값만 남는다 (조용한 함정)
scores = {"김파이": 80, "김파이": 95}
print(scores)    # 출력: {'김파이': 95}
