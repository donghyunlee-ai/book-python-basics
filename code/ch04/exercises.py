# ---- 문항 1 (해설 게재 코드 — 예시 답안) ----
profile = {"이름": "김파이", "태어난 해": 2005}
print(f"안녕하세요, {profile['이름']}입니다. 올해 {2026 - profile['태어난 해']}살이 됩니다.")
# 본문 해설: 안녕하세요, 김파이입니다. 올해 21살이 됩니다.
assert 2026 - profile['태어난 해'] == 21
profile["사는 곳"] = "서울"
print(len(profile))     # 본문 해설: 3 (쌍 2 → 3, 없는 키 할당 = 추가)
assert len(profile) == 3

# ---- 문항 2 (문항 게재 코드) ----
A = {1, 2, 3, 4, 5}
B = {4, 5, 6, 7}
print(A | B)            # 본문 해설: {1, 2, 3, 4, 5, 6, 7}
print(A & B)            # 본문 해설: {4, 5}
print(A - B)            # 본문 해설: {1, 2, 3}
print(B - A)            # 본문 해설: {6, 7}
# 게재 출력 실물 대조 (repr 자구까지)
assert repr(A | B) == "{1, 2, 3, 4, 5, 6, 7}"
assert repr(A & B) == "{4, 5}"
assert repr(A - B) == "{1, 2, 3}"
assert repr(B - A) == "{6, 7}"

# ---- 문항 3 (문항 게재 코드) ----
scores = {"김파이": 80}
scores["김 파이"] = 95  # 공백 오타 — 수정이 아니라 유령 항목 추가
print(scores)           # 본문 해설: {'김파이': 80, '김 파이': 95}
print(len(scores))      # 본문 해설: 2
assert repr(scores) == "{'김파이': 80, '김 파이': 95}"
assert len(scores) == 2 and scores["김파이"] == 80

# 문항 3 해설 — 올바른 수정 + 검증
scores = {"김파이": 80}
scores["김파이"] = 95
assert scores == {"김파이": 95}
assert len(scores) == 1                      # 해설: len이 1인지 확인
assert list(scores.keys()) == ["김파이"]     # 해설: 이름표가 하나뿐인지 확인 (3절 검증 수단)

# ---- 문항 4 (문항 게재 코드) ----
phone = {"김파이": "010-1234-5678"}
print("010-1234-5678" in phone)              # 본문 해설: False (in은 키만 본다)
assert ("010-1234-5678" in phone) is False

# 문항 4 해설 — 의도대로 고치기
print("010-1234-5678" in phone.values())     # 본문 해설: True
assert ("010-1234-5678" in phone.values()) is True

